"""Build original 4x8 bitmap glyphs from FONTSPEC.json. No BIOS font is copied."""
import json
import pathlib
base=pathlib.Path(__file__).resolve().parent.parent
spec=json.loads((base/'src/FONTSPEC.json').read_text(encoding='utf-8'))
patterns=spec['patterns']
def glyph(character):
    return [0,0]+[int(row,2)<<1 for row in patterns[character]]+[0]
fallback=[0,0,14,10,14,10,14,0]
font=[list(fallback) for _ in range(256)]
for character in patterns: font[ord(character)]=glyph(character)
# Descender pixels use the eighth raster line.
for character in 'gjpqy': font[ord(character)][7]=font[ord(character)][6]
marks={'acute':[2,4],'grave':[8,4],'circumflex':[4,10],'tilde':[6,12],'diaeresis':[10,0]}
for code,(basechar,mark,unicodechar) in spec['accents'].items():
    row=glyph(basechar)
    if mark=='cedilla': row[7]=4
    else: row[0:2]=marks[mark]
    font[int(code)]=row
font[127]=[0,4,10,14,10,10,14,0]
assert len(font)==256 and all(len(g)==8 for g in font)
assert all(0<=byte<=15 for g in font for byte in g)
data=bytes(byte for g in font for byte in g)
(base/'FONT4X8.bin').write_bytes(data)
lines=['; Original 4x8 glyphs. Generated by tools/make_font.py; edit FONTSPEC.json.',
       'font4x8:']
for code,g in enumerate(font):
    lines.append('    db '+','.join(str(v) for v in g)+' ; '+str(code))
lines+=['font4x8_end:','    assert font4x8_end-font4x8 == 2048','']
(base/'src/FONT4X8.ASM').write_text('\n'.join(lines),encoding='ascii')

records=["; Generated MSX-BR to BMP Unicode mapping.","unicode_table:"]
for code,entry in spec["accents"].items():
    point=ord(entry[2])
    records.append(" db "+str(code)+","+str(point&255)+","+str(point>>8))
records.append(" db 0")
(base/"src/UNICODE.ASM").write_text("\n".join(records)+"\n",encoding="ascii")
